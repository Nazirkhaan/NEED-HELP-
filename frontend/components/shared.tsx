/* ---------- Heatmap cell color scale ---------- */

export function heatColor(value: number | null): string {
  if (value === null || value === undefined) return "bg-slate-100 text-slate-300";
  // readiness 0..100 → red to green
  if (value >= 80) return "bg-emerald-500 text-white";
  if (value >= 65) return "bg-emerald-400 text-white";
  if (value >= 50) return "bg-amber-300 text-amber-950";
  if (value >= 35) return "bg-orange-400 text-white";
  if (value >= 20) return "bg-rose-400 text-white";
  return "bg-rose-600 text-white";
}
